// Builds real_records.json: a few sample deposits and trades that follow the rules against the
// REAL engine output (a copy of the scan's docs folder), so the screenshot harness and the logic
// tests can check the page with real market data plus user records.
// Usage: node make_real_records.mjs [--docs DIR] [--out real_records.json]
// Buy amounts are 1/8 of the account on the buy day, computed with the page's own logic block;
// shares = GBP x GBPUSD x (1 - 0.15% FX fee) / the pipeline's buy_open.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
const DOCS = arg('--docs', '/tmp/claude-0/-home-user/cfe4416a-1a27-57e3-996d-df500b1ef602/scratchpad/trk_real_docs2');
const OUT = arg('--out', join(here, 'real_records.json'));

const html = readFileSync(join(here, 'spinoff_tracker.html'), 'utf8');
const ctx = vm.createContext({});
vm.runInContext(html.match(/<script id="spin-logic">([\s\S]*?)<\/script>/)[1], ctx);
const L = ctx.SpinLogic;

export function loadDocs(dir) {
  const out = {};
  for (const col of readdirSync(dir)) {
    out[col] = {};
    for (const f of readdirSync(join(dir, col))) if (f.endsWith('.json')) out[col][f.slice(0, -5)] = JSON.parse(readFileSync(join(dir, col, f), 'utf8'));
  }
  return out;
}

const docs = loadDocs(DOCS);
const items = docs.market.pipeline.items;
const fx = docs.prices.GBPUSD;

const deposits = {};
const trades = {};
let n = 0;
const created = (d) => d + 'T18:00:00.000Z';
deposits['rd' + String(++n).padStart(3, '0')] = { date: '2025-09-22', amount_gbp: 12000, note: 'Money already in the ISA', created_at: created('2025-09-22') };
for (let m = 10; m <= 22; m++) { // Oct 2025 .. Oct 2026, first weekday of the month
  const y = 2025 + Math.floor((m - 1) / 12), mo = ((m - 1) % 12) + 1;
  let d = `${y}-${String(mo).padStart(2, '0')}-01`;
  while (L.isWeekend(d)) d = L.addDays(d, 1);
  deposits['rd' + String(++n).padStart(3, '0')] = { date: d, amount_gbp: 1666.66, note: 'Monthly deposit', created_at: created(d) };
}

function buy(ticker, note = '') {
  const it = items.find((x) => x.ticker === ticker);
  const date = it.buy_date;
  const D = L.computeAll({ today: date, todayUK: date, nowMs: Date.parse(date + 'T12:00:00Z'), market: { calendar: docs.market.calendar, pipeline: { items: [] }, status: null },
    prices: docs.prices, checks: {}, trades: Object.entries(trades).map(([id, t]) => ({ ...t, id })).filter((t) => t.date <= date), deposits: Object.entries(deposits).map(([id, d]) => ({ ...d, id })).filter((d) => d.date <= date), settings: { slice: 8 } });
  const gbp = Math.round(D.account.value / 8 * 100) / 100;
  const rate = L.priceOn(L.normSeries(fx), date);
  const shares = Math.round(gbp * rate * (1 - 0.0015) / it.buy_open * 1e4) / 1e4;
  trades['rt' + String(++n).padStart(3, '0')] = { date, type: 'buy', ticker, shares, amount_gbp: gbp, note, created_at: created(date) };
  return { date, shares, gbp };
}
function sell(ticker, date, shares, note = '') {
  const s = L.normSeries(docs.prices[ticker]);
  const usd = L.priceOn(s, date), rate = L.priceOn(L.normSeries(fx), date);
  const gbp = Math.round(shares * usd / rate * (1 - 0.0015) * 100) / 100;
  trades['rt' + String(++n).padStart(3, '0')] = { date, type: 'sell', ticker, shares, amount_gbp: gbp, note, created_at: created(date) };
}

buy('SOLS');                                   // sells 2026-11-19 by the calendar
buy('VSNT');
const rna = buy('RNA');
sell('RNA', '2026-09-15', rna.shares, 'Sold early (not the rule)'); // a closed position
buy('HONA');
buy('ADIG');

const out = {
  note: 'Sample user records for the real engine output in trk_real_docs. Generated by make_real_records.mjs.',
  deposits, trades,
  settings: { main: { index_fund: 'VUAG', slice: 8, monthly_deposit: 1666.66, dismissed: {} } }
};
writeFileSync(OUT, JSON.stringify(out, null, 1));
console.log(`wrote ${OUT}: ${Object.keys(deposits).length} deposits, ${Object.keys(trades).length} trades`);
for (const t of Object.values(trades)) console.log(`  ${t.date} ${t.type} ${t.ticker} ${t.shares} sh £${t.amount_gbp}`);
